// Stand-in for the Laptop 2 Python worker, used only for frontend/backend
// development. It answers on the real topics with schema-valid results, but
// the numbers come from a simple energy/rate formula, NOT the trained models.
// Every result says so in `model` and `warnings`, so it can't be mistaken for
// real output in the dashboard.
//
// Flags:
//   --delay=800        answer after N ms (default 600)
//   --drop             never answer (to demo the 15 s timeout)
//   --fail-every=3     every 3rd request gets an error result
import '../src/loadEnv.js';
import { randomUUID } from 'node:crypto';
import mqtt from 'mqtt';
import { check } from '../src/contracts.js';

const args = Object.fromEntries(
  process.argv.slice(2).map((a) => {
    const [k, v] = a.replace(/^--/, '').split('=');
    return [k, v ?? true];
  }),
);
const delay = Number(args.delay ?? 600);
const failEvery = Number(args['fail-every'] || 0);

const host = process.env.MQTT_HOST || '127.0.0.1';
const port = Number(process.env.MQTT_PORT || 1883);
const requests = process.env.MQTT_TOPIC_REQUESTS || 'evdt/v1/requests/charging';
const results = process.env.MQTT_TOPIC_RESULTS_CHARGING || 'evdt/v1/results/charging';

const CHARGER_MAX_KW = { 'Level 1': 1.9, 'Level 2': 11, 'DC Fast Charger': 150 };
const EFFICIENCY = 0.9;

function estimate(req) {
  const { batteryCapacityKwh } = req.vehicle;
  const { startSocPct, targetSocPct, requestedRateKw, chargerType } = req.charging;
  const energyKwh = (batteryCapacityKwh * (targetSocPct - startSocPct)) / 100 / EFFICIENCY;
  const rate = Math.min(requestedRateKw, CHARGER_MAX_KW[chargerType] ?? requestedRateKw);
  return { durationHours: +(energyKwh / rate).toFixed(4), energyKwh: +energyKwh.toFixed(4) };
}

const client = mqtt.connect(`mqtt://${host}:${port}`, {
  clientId: `stub-worker-${randomUUID().slice(0, 8)}`,
  username: process.env.STUB_MQTT_USERNAME || 'mlworker',
  password: process.env.STUB_MQTT_PASSWORD || 'dev',
});

let count = 0;
client.on('connect', () => {
  client.subscribe(requests, { qos: 1 });
  console.log(`[stub-worker] listening on ${requests} at ${host}:${port}${args.drop ? ' (dropping everything)' : ''}`);
});

client.on('message', (topic, payload) => {
  let req;
  try {
    req = JSON.parse(payload.toString());
  } catch {
    return;
  }
  count += 1;
  console.log(`[stub-worker] request ${req.requestId}`);
  if (args.drop) return;

  const base = {
    schemaVersion: '1.0',
    messageId: randomUUID(),
    requestId: req.requestId,
    processedAt: new Date().toISOString(),
  };
  let result;
  const contract = check('chargingRequest', req);
  if (!contract.ok) {
    result = { ...base, status: 'invalid_request', error: { code: 'SCHEMA_INVALID', message: contract.message } };
  } else if (failEvery && count % failEvery === 0) {
    result = { ...base, status: 'error', error: { code: 'INTERNAL_ERROR', message: 'Inference failed.' } };
  } else {
    result = {
      ...base,
      status: 'completed',
      predictions: estimate(req),
      model: { durationVersion: 'dev-stub', energyVersion: 'dev-stub' },
      warnings: ['Generated by the development stub worker (simple formula), not by the trained ML models.'],
    };
  }
  setTimeout(() => client.publish(results, JSON.stringify(result), { qos: 1 }), delay);
});
